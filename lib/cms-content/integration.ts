function step(
  id: string,
  node: string,
  tag: [string, string],
  status: "completed" | "running",
  title: [string, string],
  desc: [string, string],
  chip: string
): ContentItem {
  return {
    id,
    isActive: true,
    node,
    tagId: tag[0],
    tagEn: tag[1],
    status,
    titleId: title[0],
    titleEn: title[1],
    descId: desc[0],
    descEn: desc[1],
    chip,
  };
}

